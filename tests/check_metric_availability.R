source('app/R/metric_availability.R')
source('app/R/map_helpers.R')

schools <- read.csv('app/data/school_metrics.csv')
divisions <- read.csv('app/data/division_metrics.csv')
available <- reportable_metric_years(schools, divisions)
years_for <- function(metric) sort(available$year[available$metric_id == metric])

stopifnot(identical(years_for('test_sol_annual_overall'), 2022:2026))
stopifnot(identical(years_for('test_overall_perf_index'), 2022:2024))
stopifnot(length(years_for('test_acr_science')) == 0L)
stopifnot(identical(years_for('attendance_chronic_absent_pct'), 2023:2026))
stopifnot(identical(years_for('behavior_susp_per_100'), 2023:2024))

limits <- map_scale_limits(c(0, 100), c(40, 50, 60, 70, 80))
stopifnot(length(limits) == 2L, limits[[1]] > 0, limits[[2]] < 100)
high <- data.frame(better_direction = 'higher_better')
low <- data.frame(better_direction = 'lower_better')
stopifnot(identical(make_ramp(high), rev(make_ramp(low))))
palette <- make_palette(high, limits)
stopifnot(identical(palette(c(-100, 100)), palette(limits)))
stopifnot(identical(palette(NA_real_), '#9e9e9e'))
cat('Metric year and map scale checks passed.\n')
